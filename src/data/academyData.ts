// Helper to store and retrieve user submissions
const STORAGE_KEY = 'ilac_academy_leads';

export function getStoredLeads(): LeadSubmission[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch (e) {
    console.error('Failed to read leads from localStorage', e);
    return [];
  }
}

export function saveLeadSubmission(lead: Omit<LeadSubmission, 'id' | 'timestamp'>): LeadSubmission {
  const newLead: LeadSubmission = {
    ...lead,
    id: 'lead-' + Date.now() + '-' + Math.random().toString(36).substr(2, 5),
    timestamp: new Date().toISOString(),
  };

  try {
    const existing = getStoredLeads();
    const updated = [newLead, ...existing];
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
    console.log('[ILAC LEAD CAPTURE] Successfully registered lead to local store / Google Sheet payload buffer:', newLead);
  } catch (e) {
    console.error('Failed to save lead', e);
  }

  return newLead;
}
